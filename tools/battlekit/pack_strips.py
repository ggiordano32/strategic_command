#!/usr/bin/env python3
"""Pack the tileable wall strips (build.py PIECES_S: ws_<t>_<pp> stone, ps_<t> palisade) for the battle
view's mitred walls (game/battlekit.gd _wall_ring). Each strip is its own texture, one tile long, so the
GPU repeats it along the wall (the atlases cannot wrap).

    python3 tools/battlekit/pack_strips.py [--frames tools/battlekit/_frames] [--out assets/battlekit/strips]
        [--gd game/battlekit_strips.gd]

Reads the three-tile renders, lights them like pack.py (albedo, normal + height + mask class, 4 px/m
pre-lit for Graphics Low), cuts the middle tile (x) and the alpha box (y), writes
strips/<name>_{albedo,nrm,low}.png and the table: per strip the tile length in metres and the box in
metres (v0 = outer edge, v1 = inner edge, from the strip's centre line, +y inward).
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import kitlib  # noqa: E402
import pack  # noqa: E402

NAMES = ["ws_8_2", "ws_10_2", "ws_12_2", "ws_12_4", "ws_14_4", "ps_8", "ps_10", "ps_12"]
TILE = {"ws": 16, "ps": 12}


def main():
    args = sys.argv[1:]

    def opt(k, d):
        return args[args.index(k) + 1] if k in args else d
    frames = os.path.abspath(opt("--frames", os.path.join(HERE, "_frames")))
    out = os.path.abspath(opt("--out", os.path.join(ROOT, "assets", "battlekit", "strips")))
    gd = os.path.abspath(opt("--gd", os.path.join(ROOT, "game", "battlekit_strips.gd")))
    os.makedirs(out, exist_ok=True)
    rows = []
    for name in NAMES:
        meta = json.load(open(os.path.join(frames, name + ".json")))
        alb = kitlib.load_png(os.path.join(frames, name + "_albedo.png"))
        nrm = kitlib.load_png(os.path.join(frames, name + "_normal.png"))
        hgt = kitlib.load_png(os.path.join(frames, name + "_height.png"), 16)
        msk = kitlib.load_png(os.path.join(frames, name + "_mask.png"))
        N, ppm = meta["px"], meta["ppm"]
        tw = int(TILE[name[:2]] * ppm)
        x0 = N // 2 - tw // 2
        x1 = x0 + tw
        ys = np.nonzero(alb[:, x0:x1, 3].max(axis=1) > 0.02)[0]
        y0, y1 = int(ys.min()) - 1, int(ys.max()) + 2
        y0 -= y0 % 2
        y1 += y1 % 2
        sl = (slice(y0, y1), slice(x0, x1))
        lit, a = pack.prelit(alb, nrm, hgt, msk, meta["zmax"], ppm)
        m = msk[..., :3] * (msk[..., 3:4] > 0.5)
        mcls = np.where(m[..., 0] > 0.5, 0.7, np.where(m[..., 1] > 0.5, 0.4, np.where(m[..., 2] > 0.5, 0.1, 1.0)))
        A = alb[sl].copy()
        A[..., :3] = pack.bleed(A[..., :3], A[..., 3], 2)
        NR = np.zeros((y1 - y0, tw, 4), np.float32)
        NR[..., 0:2] = nrm[sl][..., 0:2]
        NR[..., 2] = hgt[..., 0][sl]
        NR[..., 3] = mcls[sl]
        dead = A[..., 3] < 0.02
        NR[dead, 0:2] = 0.5
        NR[dead, 2] = 0.0
        NR[dead, 3] = 1.0
        L = np.concatenate([lit, a], -1)[sl]
        h, w = y1 - y0, tw
        pl = (L[..., :3] * L[..., 3:4]).reshape(h // 2, 2, w // 2, 2, 3).mean((1, 3))
        pa = L[..., 3].reshape(h // 2, 2, w // 2, 2).mean((1, 3))
        LOW = np.concatenate([pl / np.maximum(pa[..., None], 1e-4), pa[..., None]], -1)
        LOW[..., :3] = pack.bleed(LOW[..., :3], LOW[..., 3], 2)
        kitlib.save_png(os.path.join(out, name + "_albedo.png"), A)
        kitlib.save_png(os.path.join(out, name + "_nrm.png"), NR)
        kitlib.save_png(os.path.join(out, name + "_low.png"), LOW)
        v0 = (y0 - N / 2) / ppm
        v1 = (y1 - N / 2) / ppm
        rows.append((name, TILE[name[:2]], v0, v1))
    lines = ["extends RefCounted",
             "## GENERATED by tools/battlekit/pack_strips.py: do not edit. The tileable wall strips of the battle view",
             "## (assets/battlekit/strips/<name>_{albedo,nrm,low}.png, one tile long, repeated along the wall by",
             "## game/battlekit.gd _wall_ring): per strip the tile length in metres and the texture's extent across the",
             "## wall in metres from the wall's centre line (V0 the outer edge = image top, V1 the inner edge; +y inward).",
             "", "const PPM := 8.0", "const NAMES: Array[String] = [%s]" % ", ".join('"%s"' % r[0] for r in rows),
             "## [tile, v0, v1] per strip.", "const INFO: Array = ["]
    for r in rows:
        lines.append("\t[%.1f, %.4f, %.4f],  # %s" % (r[1], r[2], r[3], r[0]))
    lines += ["]", ""]
    open(gd, "w").write("\n".join(lines))
    print("%d strips" % len(rows))


main()
